-- function: decrement_product_stock(uuid, integer)

CREATE FUNCTION public.decrement_product_stock(p_product_id uuid, p_qty integer) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
declare
  affected int;
begin
  update products
  set stock = stock - p_qty
  where id = p_product_id and stock >= p_qty;

  get diagnostics affected = row_count;
  return affected > 0;
end;
$$;

-- function: handle_new_user()

CREATE FUNCTION public.handle_new_user() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
begin
  insert into public.customer_profiles (id, email, phone, first_name, last_name)
  values (
    new.id,
    new.email,
    new.phone,
    new.raw_user_meta_data ->> 'first_name',
    new.raw_user_meta_data ->> 'last_name'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;


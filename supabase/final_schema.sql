-- view: v_category_product_counts

CREATE VIEW public.v_category_product_counts AS
 SELECT c.id AS category_id,
    c.slug,
    count(p.id) FILTER (WHERE p.is_active) AS product_count
   FROM (public.categories c
     LEFT JOIN public.products p ON ((p.category_id = c.id)))
  GROUP BY c.id, c.slug;

-- view: v_daily_sales

CREATE VIEW public.v_daily_sales AS
 SELECT date_trunc('day'::text, placed_at) AS day,
    count(*) AS order_count,
    sum(total) AS revenue
   FROM public.orders
  WHERE (payment_status = 'paid'::text)
  GROUP BY (date_trunc('day'::text, placed_at))
  ORDER BY (date_trunc('day'::text, placed_at));

